const DICTS: Record<LangCode, Dict> = { en, es, fr, de, pt, it, zh, ja };

const STORAGE_KEY = "bcradio.lang";

type I18nValue = {
  lang: LangCode;
  locale: string;
  setLang: (l: LangCode) => void;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
  nf: (n: number, opts?: Intl.NumberFormatOptions) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("en");

  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as LangCode | null;
      if (saved && DICTS[saved]) setLangState(saved);
    } catch { /* noop */ }
  }, []);

  const setLang = (l: LangCode) => {
    setLangState(l);
    try { localStorage.setItem(STORAGE_KEY, l); } catch { /* noop */ }
    if (typeof document !== "undefined") document.documentElement.lang = l;
  };

  const value = useMemo<I18nValue>(() => {
    const locale = LANGUAGES.find((l) => l.code === lang)?.locale ?? "en-US";
    const dict = DICTS[lang] ?? {};
    return {
      lang,
      locale,
      setLang,
      t: (key, vars) => {
        let s = dict[key] ?? en[key] ?? String(key);
        if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
        return s;
      },
      nf: (n, opts) => new Intl.NumberFormat(locale, opts).format(n),
    };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (ctx) return ctx;
  // Safe fallback (e.g. during isolated rendering).
  return {
    lang: "en",
    locale: "en-US",
    setLang: () => {},
    t: (key, vars) => {
      let s = en[key] ?? String(key);
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      return s;
    },
    nf: (n, opts) => new Intl.NumberFormat("en-US", opts).format(n),
  };
}
